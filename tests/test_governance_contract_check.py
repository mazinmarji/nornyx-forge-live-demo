def _not_run(gate) -> None:
    assert gate.passed is False
    assert gate.command == (), "a check that did not run recorded a command"
    assert gate.provenance["outcome"] == "not_run"
    assert gate.detail.startswith("no Nornyx check ran: ")
    refs = {ref.kind for ref in flow_evidence(
        {"accepted": False, "execution_backend": "sequential", "gates": [gate.__dict__]})}
    assert "governance_validation" not in refs


def test_a_contract_changed_after_generation_is_not_checked(tmp_path: Path):
    """The bytes Nornyx would pass are still refused: they are not the ones
    this build generated."""
    root, digest = _project(tmp_path)
    with (root / CONTRACT).open("a", encoding="utf-8", newline="") as stream:
        stream.write("# edited after generation\n")
    gate = _check(root, digest)
    _not_run(gate)
    edited = _digest((root / CONTRACT).read_bytes())
    assert "changed after generation" in gate.detail
    assert digest in gate.detail and edited in gate.detail
    assert gate.provenance["subject"]["checked_digest"] is None


def test_a_missing_contract_is_not_checked(tmp_path: Path):
    root, digest = _project(tmp_path)
    (root / CONTRACT).unlink()
    gate = _check(root, digest)
    _not_run(gate)
    assert gate.detail == (
        "no Nornyx check ran: the generated build contract .nornyx/generated/brd_contract.nyx is missing")


def test_a_directory_in_place_of_the_contract_is_not_checked(tmp_path: Path):
    root, digest = _project(tmp_path)
    (root / CONTRACT).unlink()
    (root / CONTRACT).mkdir()
    gate = _check(root, digest)
    _not_run(gate)
    assert "is not a regular file inside the project" in gate.detail


def test_a_contract_that_is_a_link_is_not_followed(tmp_path: Path):
    """A link to the same bytes elsewhere is refused before its digest is
    taken: the check is of the file the build generated, not of a pointer."""
    root, digest = _project(tmp_path)
    outside = tmp_path / "elsewhere.nyx"
    outside.write_bytes((root / CONTRACT).read_bytes())
    (root / CONTRACT).unlink()
    try:
        os.symlink(outside, root / CONTRACT)
    except (OSError, NotImplementedError) as exc:  # pragma: no cover - platform
        pytest.skip(f"symbolic links unavailable here: {exc}")
    gate = _check(root, digest)
    _not_run(gate)
    assert "is not a regular file inside the project" in gate.detail


def test_an_oversized_contract_is_not_read(tmp_path: Path):
    root, digest = _project(tmp_path)
    with (root / CONTRACT).open("ab") as stream:
        stream.truncate(gate_module.GOVERNANCE_CONTRACT_MAX_BYTES + 1)
    gate = _check(root, digest)
    _not_run(gate)
    assert "larger than" in gate.detail


