"""The greenfield governance check: `nornyx check` of the build's own contract (A-049).

The greenfield acceptance profile runs the real Nornyx CLI on the contract
the development flow generated for this build, `.nornyx/generated/brd_contract.nyx`,
and only on the bytes whose digest the flow recorded when it generated them.
Its passing result is what `experience_build.flow_evidence` translates into a
`governance_validation` reference, which READY requires.

Real or nothing: every passing case here runs the installed CLI. Fail closed:
a contract Nornyx refuses, one changed or removed after generation, one that
is not a regular file inside the project, a build that recorded no digest,
and a check that cannot run or answers in anything but Nornyx's own words
all yield a failing gate, never a passing one. The journey-level versions of
the four main negatives are in `tests/test_simulated_journey.py`.
"""

from __future__ import annotations

import hashlib
import os
import subprocess
import sys
from pathlib import Path

import pytest

from nornyx_forge import experience_build, greenfield_verifier
from nornyx_forge import gates as gate_module
from nornyx_forge.contract_generator import generate_brd_contract
from nornyx_forge.experience_build import flow_evidence
from nornyx_forge.requirements import parse_brd

CONTRACT = Path(".nornyx") / "generated" / "brd_contract.nyx"
BRD = (
    "# Business Requirements\n\n"
    "## BRD-001 Purpose\n\nKeep a list of support cases.\n\n"
    "## BRD-002 Functional requirements\n\n"
    "### BRD-F-001 Open a case\n\nA support agent opens a case with a title.\n"
)
#: Valid YAML that Nornyx refuses: the project has no name.
REFUSED = "nornyx: '0.2'\nproject: {}\n"
#: Not YAML at all: Nornyx refuses it as a parse error.
UNPARSEABLE = "nornyx: [\n"


def _digest(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def _project(tmp_path: Path) -> tuple[Path, str]:
    """A project whose contract was generated by Forge's own generator, and
    the digest a flow would have recorded for it."""
    root = tmp_path / "project"
    root.mkdir()
    (root / "BRD.md").write_text(BRD, encoding="utf-8")
    contract = generate_brd_contract(root, parse_brd(root / "BRD.md"))
    return root, _digest(contract.read_bytes())


def _replace(root: Path, text: str) -> str:
    """Write `text` as the generated contract and return its digest: the
    binding holds, so only the CLI's verdict decides."""
    target = root / CONTRACT
    target.write_text(text, encoding="utf-8", newline="")
    return _digest(target.read_bytes())


def _check(root: Path, digest: object):
    return gate_module.trusted_contract_check(root, digest)


# ---------------------------------------------------------------------------
# The passing case: the real CLI, on a private snapshot of the bound bytes
# ---------------------------------------------------------------------------

def test_the_generated_contract_passes_the_real_nornyx_check(tmp_path: Path):
    root, digest = _project(tmp_path)
    gate = _check(root, digest)
    assert gate.name == "greenfield:nornyx-contract-check"
    assert gate.passed is True and gate.returncode == 0, gate.detail
    assert gate.command[:5] == (sys.executable, "-I", "-c", gate_module.NORNYX_CHECK_BOOTSTRAP, "check")
    snapshot = Path(gate.command[5])
    assert len(gate.command) == 6 and not snapshot.resolve().is_relative_to(root.resolve())
    assert not snapshot.exists(), "the private snapshot outlived the check"
    assert gate.detail.startswith(f"nornyx check passed the generated build contract {digest}")
    assert gate.detail.endswith("Nornyx check passed")
    record = gate.provenance
    assert record["schema"] == gate_module.GOVERNANCE_CHECK_SCHEMA
    assert record["outcome"] == "passed"
    assert record["subject"] == {"path": CONTRACT.as_posix(), "generated_digest": digest,
                                 "checked_digest": digest}
    assert record["cli"]["entry"] == "nornyx.cli:main"
    assert record["invocation"]["isolated_python"] is True
    assert record["invocation"]["cwd"] == "private-temporary-directory"


def test_the_passing_check_translates_into_a_passing_governance_validation(tmp_path: Path):
    """What `flow_evidence` makes of the record: the trusted command is the
    Nornyx CLI's entry point, so the gate is a Nornyx gate, and its passing
    verdict is the governance validation's."""
    root, digest = _project(tmp_path)
    gate = _check(root, digest)
    refs = {ref.kind: ref for ref in flow_evidence(
        {"accepted": True, "execution_backend": "sequential", "gates": [gate.__dict__]})}
    assert refs["governance_validation"].passed is True
    assert experience_build.NORNYX_GATE_REF.match(refs["governance_validation"].ref)


# ---------------------------------------------------------------------------
# Nornyx refuses the contract
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("text, returncode, code", [
    (REFUSED, 1, "MISSING_PROJECT_NAME"),
    (UNPARSEABLE, 2, "PARSE_ERROR"),
])
def test_a_contract_nornyx_refuses_fails_the_gate(tmp_path: Path, text: str, returncode: int,
                                                  code: str):
    root, _ = _project(tmp_path)
    digest = _replace(root, text)
    gate = _check(root, digest)
    assert gate.passed is False and gate.returncode == returncode
    assert gate.detail.startswith(
        f"nornyx check refused the generated build contract {digest} (exit {returncode}; {code}): ")
    assert code in gate.detail
    assert gate.provenance["outcome"] == "refused"
    refs = {ref.kind: ref for ref in flow_evidence(
        {"accepted": False, "execution_backend": "sequential", "gates": [gate.__dict__]})}
    assert refs["governance_validation"].passed is False


# ---------------------------------------------------------------------------
# No check runs: the bound bytes are not there to check
# ---------------------------------------------------------------------------

def _not_run(gate) -> None:
    assert gate.passed is False
    assert gate.command == (), "a check that did not run recorded a command"
    assert gate.provenance["outcome"] == "not_run"
    assert gate.detail.startswith("no Nornyx check ran: ")
    refs = {ref.kind for ref in flow_evidence(
        {"accepted": False, "execution_backend": "sequential", "gates": [gate.__dict__]})}
    assert "governance_validation" not in refs


def test_a_contract_changed_after_generation_is_not_checked(tmp_path: Path):
    """The bytes Nornyx would pass are still refused: they are not the ones
    this build generated."""
    root, digest = _project(tmp_path)
    with (root / CONTRACT).open("a", encoding="utf-8", newline="") as stream:
        stream.write("# edited after generation\n")
    gate = _check(root, digest)
    _not_run(gate)
    edited = _digest((root / CONTRACT).read_bytes())
    assert "changed after generation" in gate.detail
    assert digest in gate.detail and edited in gate.detail
    assert gate.provenance["subject"]["checked_digest"] is None


def test_a_missing_contract_is_not_checked(tmp_path: Path):
    root, digest = _project(tmp_path)
    (root / CONTRACT).unlink()
    gate = _check(root, digest)
    _not_run(gate)
    assert gate.detail == (
        "no Nornyx check ran: the generated build contract .nornyx/generated/brd_contract.nyx is missing")


def test_a_directory_in_place_of_the_contract_is_not_checked(tmp_path: Path):
    root, digest = _project(tmp_path)
    (root / CONTRACT).unlink()
    (root / CONTRACT).mkdir()
    gate = _check(root, digest)
    _not_run(gate)
    assert "is not a regular file inside the project" in gate.detail


def test_a_contract_that_is_a_link_is_not_followed(tmp_path: Path):
    """A link to the same bytes elsewhere is refused before its digest is
    taken: the check is of the file the build generated, not of a pointer."""
    root, digest = _project(tmp_path)
    outside = tmp_path / "elsewhere.nyx"
    outside.write_bytes((root / CONTRACT).read_bytes())
    (root / CONTRACT).unlink()
    try:
        os.symlink(outside, root / CONTRACT)
    except (OSError, NotImplementedError) as exc:  # pragma: no cover - platform
        pytest.skip(f"symbolic links unavailable here: {exc}")
    gate = _check(root, digest)
    _not_run(gate)
    assert "is not a regular file inside the project" in gate.detail


def test_an_oversized_contract_is_not_read(tmp_path: Path):
    root, digest = _project(tmp_path)
    with (root / CONTRACT).open("ab") as stream:
        stream.truncate(gate_module.GOVERNANCE_CONTRACT_MAX_BYTES + 1)
    gate = _check(root, digest)
    _not_run(gate)
    assert "larger than" in gate.detail


@pytest.mark.parametrize("recorded", [None, "", "sha256:", "sha256:" + "0" * 63, 42,
                                      "SHA256:" + "0" * 64])
def test_a_build_that_recorded_no_digest_has_nothing_to_check(tmp_path: Path, recorded: object):
    root, _ = _project(tmp_path)
    gate = _check(root, recorded)
    _not_run(gate)
    assert "recorded no digest" in gate.detail


def test_an_interpreter_inside_the_project_is_not_used(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    root, digest = _project(tmp_path)
    monkeypatch.setattr(gate_module.sys, "executable", str(root / "python"))
    gate = _check(root, digest)
    _not_run(gate)
    assert "inside the provider workspace" in gate.detail


# ---------------------------------------------------------------------------
# The check errors: it ran, and its answer is not Nornyx's verdict
# ---------------------------------------------------------------------------

def _errored(gate) -> None:
    assert gate.passed is False
    assert gate.provenance["outcome"] == "errored"
    assert gate.detail.startswith("nornyx check errored on the generated build contract ")


def test_a_check_that_cannot_start_errors(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    root, digest = _project(tmp_path)
    monkeypatch.setattr(gate_module, "NORNYX_CHECK_BOOTSTRAP",
                        "import sys;sys.stderr.write('the check could not start');sys.exit(1)")
    gate = _check(root, digest)
    _errored(gate)
    assert gate.returncode == 1 and "the check could not start" in gate.detail


def test_an_exit_zero_without_nornyx_s_verdict_is_not_a_pass(tmp_path: Path,
                                                             monkeypatch: pytest.MonkeyPatch):
    """The exit status alone is a proxy: a program that exits 0 and does not
    say what Nornyx says when it passes a contract has not passed it."""
    root, digest = _project(tmp_path)
    monkeypatch.setattr(gate_module, "NORNYX_CHECK_BOOTSTRAP", "print('looks fine')")
    gate = _check(root, digest)
    _errored(gate)
    assert gate.returncode == 0


def test_a_refusal_exit_without_a_nornyx_error_is_not_a_refusal(tmp_path: Path,
                                                                monkeypatch: pytest.MonkeyPatch):
    root, digest = _project(tmp_path)
    monkeypatch.setattr(gate_module, "NORNYX_CHECK_BOOTSTRAP", "import sys;sys.exit(2)")
    _errored(_check(root, digest))


@pytest.mark.parametrize("raised, returncode", [
    (subprocess.TimeoutExpired(cmd="nornyx", timeout=1), 124),
    (OSError("cannot execute"), 2),
])
def test_a_check_that_times_out_or_cannot_execute_errors(tmp_path: Path,
                                                         monkeypatch: pytest.MonkeyPatch,
                                                         raised: Exception, returncode: int):
    root, digest = _project(tmp_path)

    def refuse(*_args, **_kwargs):
        raise raised

    monkeypatch.setattr(gate_module.subprocess, "run", refuse)
    gate = _check(root, digest)
    _errored(gate)
    assert gate.returncode == returncode


